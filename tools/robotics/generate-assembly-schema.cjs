const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const { Ajv2020 } = require(path.join(root, 'ts/node_modules/ajv/dist/2020.js'));
const standalone = require(path.join(root, 'ts/node_modules/ajv/dist/standalone/index.js')).default;
const source = 'packages/component-registry/schema/v2.sc-assembly.schema.json';
const schema = JSON.parse(fs.readFileSync(path.join(root, source), 'utf8'));
const ajv = new Ajv2020({ strict: true, strictRequired: false, code: { source: true, esm: true } });
let code = standalone(ajv, ajv.compile(schema));
let imports = '';
// Native ESM and tsx expose different CJS default shapes; normalize the helpers.
for (const helper of ['ucs2length', 'equal']) {
  if (code.includes(`require("ajv/dist/runtime/${helper}")`)) {
    imports += `import ${helper}Module from "ajv/dist/runtime/${helper}.js";\nconst ${helper}Runtime = typeof ${helper}Module === "function" ? ${helper}Module : ${helper}Module.default;\n`;
    code = code.replaceAll(`require("ajv/dist/runtime/${helper}").default`, `${helper}Runtime`);
  }
}
if (code.includes('require(')) throw new Error('Unreviewed standalone runtime dependency');
const outputs = {
  'robotAssemblySchema.ts': `// Generated from ${source}. Do not edit.\nexport const ROBOT_ASSEMBLY_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;\n`,
  'robotAssemblyValidator.ts': `// @ts-nocheck\n// Generated by Ajv 8.17.1 from ${source}; no runtime code generation.\n${imports}${code}\n`,
};
for (const [name, result] of Object.entries(outputs)) {
  const target = path.join(root, 'ts/packages/contracts/src', name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== result) {
      throw new Error(`${name} is stale; run tools/robotics/generate-assembly-schema.cjs`);
    }
  } else fs.writeFileSync(target, result);
}
